package com.undal.syl.app.features.auth

import android.content.Context
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import androidx.credentials.exceptions.GetCredentialException
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import kotlinx.coroutines.CancellationException

/** Credential Manager owns account selection and OAuth; only the ID token goes to Firebase. */
object GoogleSignIn {
    suspend fun idToken(context: Context): String {
        // Generated by the Google Services plugin from the Web OAuth client
        // (client_type 3), NOT the Android OAuth client or Firebase API key.
        val resource = context.resources.getIdentifier("default_web_client_id", "string", context.packageName)
        val clientId = if (resource != 0) context.getString(resource) else ""
        check(clientId.endsWith(".apps.googleusercontent.com")) {
            "Google sign-in is not configured in this build. Add the app signing fingerprints in Firebase, download the updated google-services.json, and rebuild."
        }
        val option = GetSignInWithGoogleOption.Builder(clientId).build()
        val response = CredentialManager.create(context).getCredential(
            context = context,
            request = GetCredentialRequest.Builder().addCredentialOption(option).build()
        )
        val credential = response.credential
        check(credential is CustomCredential && credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
            "Google did not return a supported sign-in credential. Please try again."
        }
        return GoogleIdTokenCredential.createFrom(credential.data).idToken
    }

    /** Deliberate dismissal is not an authentication failure. No raw tokens/errors are shown. */
    fun errorMessage(error: Exception): String? = when (error) {
        is GetCredentialCancellationException -> null
        is CancellationException -> throw error
        is GetCredentialException -> "Google sign-in could not finish. Check your connection and Google Play services, then try again. If it keeps failing, check this build's OAuth client and signing fingerprints."
        is IllegalStateException -> error.message
        else -> "Google sign-in could not finish. Please try again or use email and password."
    }
}
